import com.google.protobuf.gradle.id

plugins {
    `java-library`
    id("ekbatan.publishing")
    id("com.google.protobuf") version "0.10.0"
}

ekbatanPublishing {
    artifactId.set("ekbatan-action-event-protobuf")
    description.set("Protobuf wire-format ActionEvent (Kafka consumer-side deserialization for Ekbatan outbox).")
}

java {
    sourceCompatibility = JavaVersion.VERSION_25
    targetCompatibility = JavaVersion.VERSION_25
    toolchain {
        languageVersion.set(JavaLanguageVersion.of(25))
    }
}

repositories {
    mavenCentral()
}

dependencies {
    api("com.google.protobuf:protobuf-java:${project.property("protobufVersion")}")
}

protobuf {
    protoc {
        artifact = "com.google.protobuf:protoc:${project.property("protobufVersion")}"
    }
    generateProtoTasks {
        all().configureEach {
            // Also emit a FileDescriptorSet (.desc) we can expose for runtime use.
            generateDescriptorSet = true
            descriptorSetOptions.includeImports = true
        }
    }
}

// The only Java source in this module is generated by protoc (build/generated/sources/proto/main/).
// Suppress the doclint "missing comment" check so we don't warn on hundreds of generated members —
// the generated code still appears in javadoc, keeping the javadoc jar non-empty for Maven Central.
tasks.named<Javadoc>("javadoc") {
    (options as StandardJavadocDocletOptions).addStringOption("Xdoclint:-missing", "-quiet")
}

// Expose the generated descriptor file so consumers (SMT, integration tests) can mount it.
val actionEventDescriptor: Configuration by configurations.creating {
    isCanBeConsumed = true
    isCanBeResolved = false
}

val descriptorFile =
    layout.buildDirectory.file("generated/sources/proto/main/descriptor_set.desc")

artifacts {
    add(actionEventDescriptor.name, descriptorFile) {
        builtBy(tasks.named("generateProto"))
    }
}

// Ship the compiled descriptor set inside the published jar, alongside the ActionEvent.proto the
// protobuf plugin already puts there. The SMT loads this file by path at runtime - the connector
// will not start without it - and until now it existed only as the Gradle configuration above,
// which is reachable from other modules in this build and from nobody consuming us via Maven. The
// README consequently had to tell operators to build it from source.
//
// Renamed from protoc's generic descriptor_set.desc so the jar reads ActionEvent.proto /
// ActionEvent.desc, and so two descriptors never collide if a second one is ever added.
tasks.processResources {
    from(descriptorFile) { rename { "ActionEvent.desc" } }
    dependsOn(tasks.named("generateProto"))
}
