plugins {
    `java-library`
    id("ekbatan.publishing")
    id("com.github.davidmc24.gradle.plugin.avro") version "1.9.1"
}

ekbatanPublishing {
    artifactId.set("ekbatan-action-event-avro")
    description.set("Avro wire-format ActionEvent (Kafka consumer-side deserialization for Ekbatan outbox).")
}

java {
    sourceCompatibility = JavaVersion.VERSION_25
    targetCompatibility = JavaVersion.VERSION_25
    toolchain {
        languageVersion.set(JavaLanguageVersion.of(25))
    }
}

repositories {
    mavenCentral()
}

dependencies {
    api("org.apache.avro:avro:${project.property("avroVersion")}")

    // Avro uses Jackson 2 inside and asks for 2.22.1, which has known vulnerabilities. Declaring
    // the three Jackson 2 jars here lifts them for every app using this module. All three, because
    // Maven takes the version declared closest to the app: jackson-databind alone would leave
    // jackson-core on Avro's 2.22.1. Jackson 3 (tools.jackson) is a separate library, untouched.
    val jackson2 = project.property("jackson2Version").toString()
    api("com.fasterxml.jackson.core:jackson-annotations:${jackson2.substringBeforeLast('.')}")
    api("com.fasterxml.jackson.core:jackson-core:$jackson2")
    api("com.fasterxml.jackson.core:jackson-databind:$jackson2")

    testImplementation(platform("org.junit:junit-bom:${project.property("junitBomVersion")}"))
    testImplementation("org.junit.jupiter:junit-jupiter")
    testImplementation("org.assertj:assertj-core:${project.property("assertjVersion")}")
    testRuntimeOnly("org.junit.platform:junit-platform-launcher:${project.property("junitPlatformLauncherVersion")}")
}

// Ship ActionEvent.avsc inside the published jar. Only the generated classes were published, so
// the schema itself existed nowhere a consumer could fetch it - yet the SMT needs it as a file on
// the Kafka Connect worker, and a non-JVM consumer needs it to generate their own code. The
// `actionEventSchema` configuration below shares it with other modules in this build, which does
// nothing for anyone consuming from Maven.
//
// The protobuf sibling already behaves this way: its plugin puts src/main/proto on the resource
// path, so ActionEvent.proto lands at the jar root. This makes the two modules match.
sourceSets.main {
    resources.srcDir(layout.projectDirectory.dir("src/main/avro"))
}

// Avro decodes only into classes on its allow-list (since 1.12.2), and ActionEvent is generated, so it
// cannot add itself there. This puts a call to AvroAllowList.allow in its static setup, right after its
// model is created and before anything can decode one. The build fails if Avro's generator stops
// writing the line it goes after.
tasks.named("generateAvroJava") {
    doLast {
        val source =
            layout.buildDirectory
                .file("generated-main-avro-java/io/ekbatan/events/streaming/actionevent/avro/ActionEvent.java")
                .get()
                .asFile
        val anchor = "  private static final SpecificData MODEL\$ = new SpecificData();\n"
        val text = source.readText()
        check(text.contains(anchor)) { "ActionEvent.java no longer has the line the allow-list call goes after: $anchor" }
        source.writeText(text.replace(anchor, anchor + "  static { AvroAllowList.allow(ActionEvent.class); }\n"))
    }
}

// Besides AvroAllowList, the Java source in this module is generated by the Avro plugin (build/generated-main-avro-java/).
// Suppress the doclint "missing comment" check so we don't warn on hundreds of generated members —
// the generated code still appears in javadoc, keeping the javadoc jar non-empty for Maven Central.
tasks.named<Javadoc>("javadoc") {
    (options as StandardJavadocDocletOptions).addStringOption("Xdoclint:-missing", "-quiet")
}

// Expose the .avsc file as a named output so consumers (e.g. the SMT integration test) can
// resolve its absolute path to mount into containers, instead of hardcoding a relative path.
val actionEventSchema: Configuration by configurations.creating {
    isCanBeConsumed = true
    isCanBeResolved = false
}

artifacts {
    add(actionEventSchema.name, layout.projectDirectory.file("src/main/avro/ActionEvent.avsc"))
}
